fun main() {
    ///Arithmetic Operators
    var num1 = 10
    var num2 = 5

    println(num1 + num2)
    println(num1 * num2)
    println(num1 / num2)
    println(num1 - num2)
    println(num1 % num2)///modulus

    ///Comparison Operators
    var x = 80
    var y =34

    println(x > y)
    println(x < y)
    println(x >= y)
    println(x <= y)
    println(x == y)///Equal to
    println(x != y)///Not Equal to

    ///Assignment Operators
    var number =100
    println(number)

    number +=2
    println(number)

    ///Logical Operators-&&, //, !

    println( 100==50 && 100 > 30 )
    println( 100==50 || 100 > 30 )
    println(!(100==50 || 100 > 30))
}